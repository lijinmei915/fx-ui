#!/usr/bin/env node
import crypto from "node:crypto"
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { chromium } from "@playwright/test"
import { buildPublicStylingHooks } from "./lib/fds-public-hooks.mjs"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const readText = (file) => fs.readFileSync(path.join(root, file), "utf8")
const readJson = (file) => JSON.parse(readText(file))
const foundationPath = "theme/foundation.css"
const semanticPath = "theme/fds-semantic.css"
const componentPath = "theme/fds-components.css"
const entryPath = "theme/fx-theme.css"
const presetPath = "docs/data/theme-presets.manifest.json"
const namingPath = "docs/data/token-naming.manifest.json"
const semanticContractPath = "docs/data/fds-semantic.manifest.json"
const componentContractPath = "docs/data/fds-components.manifest.json"
const cssOutputPath = "registry/fx-theme.css"
const jsonOutputPath = "registry/fx-theme.contract.json"
const shadcnOutputPath = "registry/fx-theme.json"

const foundation = readText(foundationPath)
const semantic = readText(semanticPath)
const components = readText(componentPath)
const entry = readText(entryPath)
const presets = readJson(presetPath)
const naming = readJson(namingPath)
const semanticContract = readJson(semanticContractPath)
const componentContract = readJson(componentContractPath)
const hash = (value) => crypto.createHash("sha256").update(value).digest("hex")
const stylingHooks = buildPublicStylingHooks({ naming, semantic: semanticContract, components: componentContract })

const externalImports = [...entry.matchAll(/^@import\s+(?!["']\.\/)[^;]+;\s*$/gm)].map((match) => match[0].trim())
const entryBody = entry.replace(/^@import\s+[^;]+;\s*/gm, "").trim()
const publicCss = [
  `/* fx-ui theme ${presets.contractVersion}; generated by scripts/build-theme-artifacts.mjs. */`,
  externalImports.join("\n"),
  foundation.trim(),
  semantic.trim(),
  components.trim(),
  entryBody,
  "",
].join("\n\n")

const shadcnVariables = [
  "background", "foreground", "card", "card-foreground", "popover", "popover-foreground",
  "primary", "primary-foreground", "secondary", "secondary-foreground", "muted", "muted-foreground",
  "accent", "accent-foreground", "destructive", "destructive-foreground", "border", "input", "ring",
  "sidebar", "sidebar-foreground", "sidebar-primary", "sidebar-primary-foreground", "sidebar-accent",
  "sidebar-accent-foreground", "sidebar-border", "sidebar-ring",
  "chart-1", "chart-2", "chart-3", "chart-4", "chart-5", "chart-6", "chart-7", "chart-8", "chart-9", "chart-10",
]

async function buildShadcnRegistry() {
  const browser = await chromium.launch()
  const page = await browser.newPage()
  await page.setContent(`<style>${publicCss}</style>`)
  const cssVars = {}
  try {
    for (const mode of presets.publication.publishedModes) {
      cssVars[mode] = await page.evaluate(({ mode, variables }) => {
        document.documentElement.className = mode === "dark" ? "dark" : ""
        const toHex = (value) => value.toString(16).padStart(2, "0").toUpperCase()
        return Object.fromEntries(variables.map((name) => {
          const probe = document.createElement("i")
          probe.style.backgroundColor = `var(--${name})`
          document.body.append(probe)
          const computed = getComputedStyle(probe).backgroundColor
          const canvas = document.createElement("canvas")
          canvas.width = 1
          canvas.height = 1
          const context = canvas.getContext("2d", { willReadFrequently: true })
          context.clearRect(0, 0, 1, 1)
          context.fillStyle = computed
          context.fillRect(0, 0, 1, 1)
          const [red, green, blue, alpha] = context.getImageData(0, 0, 1, 1).data
          probe.remove()
          if (alpha === 0) throw new Error(`Unable to resolve --${name} in ${mode}`)
          const value = alpha === 255
            ? `#${toHex(red)}${toHex(green)}${toHex(blue)}`
            : `rgb(${red} ${green} ${blue} / ${(alpha / 255).toFixed(3).replace(/0+$/, "").replace(/\.$/, "")})`
          return [name, value]
        }))
      }, { mode, variables: shadcnVariables })
    }
  } finally {
    await browser.close()
  }
  return `${JSON.stringify({
    $schema: "https://ui.shadcn.com/schema/registry-item.json",
    name: "fx-theme",
    type: "registry:theme",
    cssVars,
  }, null, 2)}\n`
}

const shadcnOutput = await buildShadcnRegistry()

const contract = {
  schemaVersion: 1,
  format: "fx-ui/theme-artifact",
  name: "fx-theme",
  version: presets.contractVersion,
  algorithm: presets.algorithm,
  modes: presets.publication,
  defaults: presets.defaults,
  dimensions: presets.dimensions,
  profiles: presets.profiles,
  runtimeOutputs: presets.runtimeOutputs,
  stylingHooks,
  artifacts: {
    css: { path: cssOutputPath, sha256: hash(publicCss) },
    shadcnRegistry: { path: shadcnOutputPath, format: "registry:theme", sha256: hash(shadcnOutput) },
  },
  derivedFrom: [foundationPath, semanticPath, componentPath, entryPath, presetPath, namingPath, semanticContractPath, componentContractPath],
  sourceIntegrity: {
    foundation: hash(foundation),
    semantic: hash(semantic),
    components: hash(components),
    entry: hash(entry),
    presets: hash(readText(presetPath)),
    naming: hash(readText(namingPath)),
    semanticContract: hash(readText(semanticContractPath)),
    componentContract: hash(readText(componentContractPath)),
  },
}

const jsonOutput = `${JSON.stringify(contract, null, 2)}\n`
const expected = new Map([[cssOutputPath, publicCss], [jsonOutputPath, jsonOutput], [shadcnOutputPath, shadcnOutput]])

if (process.argv.includes("--check")) {
  const stale = [...expected].filter(([file, content]) => !fs.existsSync(path.join(root, file)) || readText(file) !== content).map(([file]) => file)
  if (stale.length) {
    console.error(`Theme artifacts are stale: ${stale.join(", ")}. Run npm run build:theme-artifacts.`)
    process.exit(1)
  }
  console.log(`theme artifacts check passed: v${contract.version}, ${contract.modes.publishedModes.length} published mode(s)`)
} else {
  for (const [file, content] of expected) fs.writeFileSync(path.join(root, file), content)
  console.log(`built ${cssOutputPath} + ${jsonOutputPath} + ${shadcnOutputPath}: v${contract.version}`)
}
