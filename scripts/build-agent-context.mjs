#!/usr/bin/env node
// 生成一个短、可再生的 Agent 入口索引；AGENTS.md 仍是行为规则真相源。
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const read = (file) => JSON.parse(fs.readFileSync(path.join(root, file), "utf8"))
const tokens = read("docs/data/agent-tokens.manifest.json")
const components = read("docs/data/agent-components.manifest.json")
const buildKit = read("docs/data/page-build-kit.manifest.json")
const recipes = read("docs/data/agent-recipes.manifest.json")
const outputPath = path.join(root, "docs/data/agent-context.md")

const readyPages = buildKit.archetypes.filter((item) => item.status === "ready")
const output = `<!-- generated by scripts/build-agent-context.mjs; do not edit -->
# fx-ui Agent Quick Context

Read AGENTS.md first for mandatory governance. This file is a compact lookup index, not a replacement for source code or policy.

## Query

\`npm run fx -- search <intent> --json\`
\`npm run fx -- recipe <intent> --json\`
\`npm run fx -- plan <intent> [--name <实体名称> --slug <slug>] --json\`
\`npm run fx -- impact component <Name> --json\`
\`npm run fx -- impact token <id|cssVar> --json\`
\`npm run fx -- theme show --json\`
\`npm run fx -- theme audit --json\`
\`npm run fx -- component <Name> --json\`
\`npm run fx -- build <archetype> --json\`
\`npm run fx -- token <query> --json\`
\`npm run fx -- init --agent codex|claude|cursor --json\`
\`npm run fx -- doctor --json\`

## Current Facts

- Components: ${components.components.length} (${components.components.filter((item) => item.layer === "ui").length} ui, ${components.components.filter((item) => item.layer === "fx").length} fx)
- Semantic tokens: ${tokens.semanticTokens.length}
- Ready page archetypes: ${readyPages.map((item) => item.id).join(", ") || "none"}
- Proven recipes: ${recipes.recipes.length}
- Token policy: choose semantic tokens or declared component state mappings; never pick primitive palette values.
- Page policy: use a ready generator/block as-is; needs-block means stop and create the block through governance.

## Ready Build Path

${readyPages.map((item) => `- **${item.name}**: \`${item.generator}\`\n  Frame: ${item.frame.join(" -> ")}`).join("\n")}
`
if (process.argv.includes("--check")) {
  if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, "utf8") !== output) {
    console.error("agent quick context is stale. Run: npm run build:agent")
    process.exit(1)
  }
  console.log("agent quick context check passed")
} else {
  fs.writeFileSync(outputPath, output)
  console.log("built docs/data/agent-context.md")
}
