#!/usr/bin/env node
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const sourcePath = "tokens/source/semantic.tokens.json"
const runtimePath = "theme/fds-semantic.css"
const contractPath = "docs/data/fds-semantic.manifest.json"
const foundationPath = "docs/data/fds-foundation.manifest.json"
const read = (file) => fs.readFileSync(path.join(root, file), "utf8")
const source = JSON.parse(read(sourcePath))
const foundation = JSON.parse(read(foundationPath))
const meta = source.$extensions?.fds ?? {}
const errors = []

if (meta.format !== "fds/semantic-token-source" || meta.truthSource !== sourcePath || meta.layer !== "semantic") {
  errors.push("Semantic source metadata is invalid")
}

const foundationNames = new Set((foundation.tokens ?? []).map((token) => token.name))
const tokenRows = (source.tokens ?? []).map((token) => ({
  id: token.id,
  type: token.$type,
  name: token.$extensions?.fds?.cssName,
  value: token.$value,
  modes: token.$extensions?.fds?.modes ?? {},
  aliases: token.$extensions?.fds?.aliases ?? [],
  visibility: token.$extensions?.fds?.visibility ?? "public-global",
  stability: token.$extensions?.fds?.stability ?? "experimental",
  derivation: token.$extensions?.fds?.derivation ?? null,
  rawValueReason: token.$extensions?.fds?.rawValueReason ?? null,
}))
for (const color of source.dataColors ?? []) {
  tokenRows.push({
    id: color.name.replace(/^--fds-g-/, "").replaceAll("-", "."),
    type: "color",
    name: color.name,
    value: color.value,
    modes: {},
    aliases: [color.alias],
    visibility: "public-global",
    stability: "experimental",
    rawValueReason: color.rawValueReason,
    derivation: null,
  })
}

const names = new Set()
const declaredNames = new Set(tokenRows.map((token) => token.name))
const aliases = new Set()
const cssVarPattern = /var\((--fds-g-[a-z0-9-]+)\)/g
const rawColorPattern = /(?:#[0-9a-f]{3,8}\b|\brgba?\(|\bhsl[a]?\()/i
for (const token of tokenRows) {
  if (!token.id || !token.type || !token.name || token.value == null) errors.push(`Semantic token missing required field: ${JSON.stringify(token)}`)
  if (!/^--fds-g-[a-z0-9]+(?:-[a-z0-9]+)*$/.test(token.name ?? "")) errors.push(`Invalid semantic name: ${token.name}`)
  if (names.has(token.name)) errors.push(`Duplicate semantic name: ${token.name}`)
  names.add(token.name)
  for (const alias of token.aliases) {
    if (!/^--[a-z0-9]+(?:-[a-z0-9]+)*(?:--[a-z0-9]+(?:-[a-z0-9]+)*)?$/.test(alias)) errors.push(`Invalid compatibility alias: ${alias}`)
    if (aliases.has(alias)) errors.push(`Duplicate compatibility alias: ${alias}`)
    aliases.add(alias)
  }
  for (const value of [token.value, ...Object.values(token.modes)]) {
    if (rawColorPattern.test(value) && !token.rawValueReason) errors.push(`${token.name} contains a raw color without rawValueReason`)
    for (const match of value.matchAll(cssVarPattern)) {
      if (!foundationNames.has(match[1]) && !declaredNames.has(match[1])) errors.push(`${token.name} references unknown FDS token ${match[1]}`)
    }
    if (/var\(--fx-/.test(value)) errors.push(`${token.name} may not reference legacy --fx-* variables`)
  }
}

for (const alias of source.compatibility?.aliases ?? []) {
  if (aliases.has(alias.name)) errors.push(`Duplicate compatibility alias: ${alias.name}`)
  aliases.add(alias.name)
  if (!names.has(alias.target)) errors.push(`Compatibility alias ${alias.name} targets unknown token ${alias.target}`)
}

if (errors.length) {
  console.error(`FDS Semantic source has ${errors.length} error(s):`)
  for (const error of errors) console.error(`ERROR: ${error}`)
  process.exit(1)
}

const lines = [
  `/* Generated by scripts/build-fds-semantic.mjs from ${sourcePath}. Do not edit. */`,
  ":root {",
  ...tokenRows.map((token) => `  ${token.name}: ${token.value};`),
  "",
  "  /* Legacy fx-ui and shadcn compatibility aliases. */",
  ...tokenRows.flatMap((token) => token.aliases.map((alias) => `  ${alias}: var(${token.name});`)),
  ...(source.compatibility?.aliases ?? []).map((alias) => `  ${alias.name}: var(${alias.target});`),
  "}",
]
const darkRows = tokenRows.filter((token) => token.modes.dark)
if (darkRows.length) {
  lines.push("", ".dark {", ...darkRows.map((token) => `  ${token.name}: ${token.modes.dark};`), "}")
}
lines.push("")
const runtime = lines.join("\n")

const contract = {
  schemaVersion: 1,
  format: "fds/semantic-contract",
  contractVersion: meta.contractVersion,
  truthSource: sourcePath,
  generatedRuntime: runtimePath,
  layer: "semantic",
  owner: meta.owner,
  authoring: meta.authoring,
  counts: {
    tokens: tokenRows.length,
    publicGlobal: tokenRows.filter((token) => token.visibility === "public-global").length,
    internal: tokenRows.filter((token) => token.visibility === "internal").length,
    darkOverrides: darkRows.length,
    compatibilityAliases: aliases.size,
    rawMigrationExceptions: tokenRows.filter((token) => token.rawValueReason).length,
  },
  modes: ["light", "dark"],
  tokens: tokenRows,
  compatibility: {
    policy: "aliases-reference-fds-truth-no-duplicated-values",
    legacyPrefix: "--fx-",
    shadcnSlots: "unprefixed aliases remain implementation compatibility only",
    aliases: source.compatibility?.aliases ?? [],
  },
}
const contractOutput = `${JSON.stringify(contract, null, 2)}\n`
const expected = new Map([[runtimePath, runtime], [contractPath, contractOutput]])

if (process.argv.includes("--check")) {
  const stale = [...expected].filter(([file, content]) => !fs.existsSync(path.join(root, file)) || read(file) !== content).map(([file]) => file)
  if (stale.length) {
    console.error(`FDS Semantic artifacts are stale: ${stale.join(", ")}. Run npm run build:fds-semantic.`)
    process.exit(1)
  }
  console.log(`fds semantic check passed: ${tokenRows.length} tokens, ${aliases.size} aliases, ${darkRows.length} dark overrides`)
} else {
  for (const [file, content] of expected) fs.writeFileSync(path.join(root, file), content)
  console.log(`built FDS Semantic: ${tokenRows.length} tokens, ${aliases.size} aliases, ${darkRows.length} dark overrides`)
}
