#!/usr/bin/env node
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const sourcePath = "tokens/source/component.tokens.json"
const runtimePath = "theme/fds-components.css"
const contractPath = "docs/data/fds-components.manifest.json"
const foundationPath = "docs/data/fds-foundation.manifest.json"
const semanticPath = "docs/data/fds-semantic.manifest.json"
const read = (file) => fs.readFileSync(path.join(root, file), "utf8")
const source = JSON.parse(read(sourcePath))
const foundation = JSON.parse(read(foundationPath))
const semantic = JSON.parse(read(semanticPath))
const meta = source.$extensions?.fds ?? {}
const errors = []

if (meta.format !== "fds/component-token-source" || meta.truthSource !== sourcePath || meta.layer !== "component") {
  errors.push("Component source metadata is invalid")
}

const referenceLayers = new Map([
  ...(foundation.tokens ?? []).map((token) => [token.name, token.layer]),
  ...(semantic.tokens ?? []).map((token) => [token.name, "semantic"]),
])
const admissions = new Map((source.admissions ?? []).map((admission) => [admission.component, admission]))
const requiredEvidence = ["owner", "independentThemingNeed", "semanticGap", "crossContextReuse", "documentation", "contractTest", "visualTest"]
for (const admission of source.admissions ?? []) {
  for (const field of requiredEvidence) {
    if (!admission[field] || (Array.isArray(admission[field]) && admission[field].length === 0)) {
      errors.push(`${admission.component ?? "unknown"} admission lacks ${field}`)
    }
  }
}

const rows = (source.tokens ?? []).map((token) => ({
  id: token.id,
  type: token.$type,
  name: token.$extensions?.fds?.cssName,
  component: token.$extensions?.fds?.component,
  value: token.$value,
  visibility: token.$extensions?.fds?.visibility,
  stability: token.$extensions?.fds?.stability,
}))
const names = new Set()
for (const token of rows) {
  if (!token.id || !token.type || !token.name || !token.component || !token.value) errors.push(`Component token missing required field: ${JSON.stringify(token)}`)
  if (!/^--fds-c-[a-z0-9]+(?:-[a-z0-9]+)*$/.test(token.name ?? "")) errors.push(`Invalid component name: ${token.name}`)
  if (names.has(token.name)) errors.push(`Duplicate component token: ${token.name}`)
  names.add(token.name)
  if (!admissions.has(token.component)) errors.push(`${token.name} has no component admission`)
  if (token.visibility !== "public-component") errors.push(`${token.name} must be public-component`)
  const references = [...token.value.matchAll(/var\((--fds-[gc]-[a-z0-9-]+)\)/g)].map((match) => match[1])
  if (references.length !== 1 || token.value !== `var(${references[0]})`) errors.push(`${token.name} must be a single FDS reference`)
  const referenceLayer = referenceLayers.get(references[0])
  if (!referenceLayer) errors.push(`${token.name} references unknown token ${references[0]}`)
  if (!new Set(["primitive", "semantic"]).has(referenceLayer)) errors.push(`${token.name} may reference only Primitive or Semantic, received ${referenceLayer}`)
}

if (errors.length) {
  console.error(`FDS Component source has ${errors.length} error(s):`)
  for (const error of errors) console.error(`ERROR: ${error}`)
  process.exit(1)
}

const runtime = [
  `/* Generated by scripts/build-fds-components.mjs from ${sourcePath}. Do not edit. */`,
  ":root {",
  ...rows.map((token) => `  ${token.name}: ${token.value};`),
  "}",
  "",
].join("\n")
const contract = {
  schemaVersion: 1,
  format: "fds/component-contract",
  contractVersion: meta.contractVersion,
  truthSource: sourcePath,
  generatedRuntime: runtimePath,
  layer: "component",
  owner: meta.owner,
  authoring: meta.authoring,
  counts: {
    tokens: rows.length,
    components: admissions.size,
    publicComponent: rows.filter((token) => token.visibility === "public-component").length,
  },
  admissions: source.admissions,
  tokens: rows,
}
const contractOutput = `${JSON.stringify(contract, null, 2)}\n`
const expected = new Map([[runtimePath, runtime], [contractPath, contractOutput]])

if (process.argv.includes("--check")) {
  const stale = [...expected].filter(([file, content]) => !fs.existsSync(path.join(root, file)) || read(file) !== content).map(([file]) => file)
  if (stale.length) {
    console.error(`FDS Component artifacts are stale: ${stale.join(", ")}. Run npm run build:fds-components.`)
    process.exit(1)
  }
  console.log(`fds component check passed: ${rows.length} hooks across ${admissions.size} components`)
} else {
  for (const [file, content] of expected) fs.writeFileSync(path.join(root, file), content)
  console.log(`built FDS Components: ${rows.length} hooks across ${admissions.size} components`)
}
